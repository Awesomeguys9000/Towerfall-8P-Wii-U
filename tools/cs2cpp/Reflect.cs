using Microsoft.CodeAnalysis;
using System.Text;

// Emits tf_reflection.cpp: Type metadata (fields, properties, parameterless methods,
// attributes) and GC root registration for static fields.
static class Reflect
{
    public static string Emit(Decls decls, Bodies bodies)
    {
        var sb = new StringBuilder();
        var roots = new StringBuilder();
        sb.AppendLine("// Generated by cs2cpp. Do not edit.");
        sb.AppendLine("#include \"tf_all.h\"");
        sb.AppendLine("using ::System::Object;");
        int fn = 0;
        var regs = new List<string>();
        foreach (var t in decls.Types.OrderBy(x => x.ToDisplayString()))
        {
            if (t.TypeKind != TypeKind.Class && t.TypeKind != TypeKind.Struct && t.TypeKind != TypeKind.Enum) continue;
            if (Decls.IsGenericType(t)) continue;
            var cn = Names.ClassName(t);
            var tt = Names.Type(t);
            bool hasCinit = decls.HasStaticInit(t);
            string guard = hasCinit ? "(" + cn + "::__cinit(), 0), " : "";
            var f = new StringBuilder();
            f.AppendLine("static void __reg" + fn + "() {");
            f.AppendLine("  auto* t = ::sys::typeof_<" + tt + ">();");
            f.AppendLine("  ::sys::type_set_name(t, u\"" + t.Name + "\", u\"" + t.ToDisplayString() + "\");");
            if (t.TypeKind == TypeKind.Enum) { f.AppendLine("}"); sb.Append(f); regs.Add("__reg" + fn); fn++; continue; }
            if (t.BaseType != null && Names.IsOurs(t.BaseType) && !Decls.IsGenericType(t.BaseType))
                f.AppendLine("  t->baseType = ::sys::typeof_<" + Names.Type(t.BaseType) + ">();");
            bool isStruct = t.TypeKind == TypeKind.Struct;
            string self = isStruct ? "::sys::unbox<" + cn + ">(o)" : "::sys::cast<" + tt + ">(o)";
            string selfAcc = isStruct ? "." : "->";
            foreach (var m in t.GetMembers())
            {
                if (m is IFieldSymbol fld && !fld.IsImplicitlyDeclared && fld.DeclaredAccessibility == Accessibility.Public)
                {
                    var ft = Names.Type(fld.Type);
                    string get, set = "nullptr";
                    if (fld.IsConst)
                        get = "[](Object*) -> Object* { return ::sys::box_any<" + ft + ">(" + bodies.Const(fld.ConstantValue, fld.Type) + "); }";
                    else if (fld.IsStatic)
                    {
                        get = "[](Object*) -> Object* { return " + guard + "::sys::box_any<" + ft + ">(" + cn + "::" + Names.Id(fld.Name) + "); }";
                        if (!fld.IsReadOnly) set = "[](Object*, Object* v) { " + cn + "::" + Names.Id(fld.Name) + " = ::sys::unbox_any<" + ft + ">(v); }";
                    }
                    else
                    {
                        get = "[](Object* o) -> Object* { return ::sys::box_any<" + ft + ">(" + self + selfAcc + Names.Id(fld.Name) + "); }";
                        if (!isStruct) set = "[](Object* o, Object* v) { " + self + "->" + Names.Id(fld.Name) + " = ::sys::unbox_any<" + ft + ">(v); }";
                    }
                    var attrs = Attrs(fld, bodies);
                    f.AppendLine("  t->AddField(u\"" + fld.Name + "\", ::sys::typeof_<" + ft + ">(), " + (fld.IsStatic || fld.IsConst ? "true" : "false") + ", " + (fld.IsConst ? "true" : "false") + ",");
                    f.AppendLine("    " + get + ",");
                    f.AppendLine("    " + set + ",");
                    f.AppendLine("    " + (attrs == null ? "nullptr" : "[]() -> ::System::Array<Object*>* { return ::System::Array<Object*>::Of({" + attrs + "}); }") + ");");
                }
                else if (m is IPropertySymbol p && !p.IsStatic && !p.IsIndexer && p.DeclaredAccessibility == Accessibility.Public
                         && p.GetMethod != null && p.SetMethod != null && p.GetMethod.DeclaredAccessibility == Accessibility.Public
                         && p.SetMethod.DeclaredAccessibility == Accessibility.Public && !isStruct)
                {
                    var pt = Names.Type(p.Type);
                    string get, set;
                    if (Decls.IsFieldLike(p))
                    {
                        get = "[](Object* o) -> Object* { return ::sys::box_any<" + pt + ">(" + self + "->" + Names.Id(p.Name) + "); }";
                        set = "[](Object* o, Object* v) { " + self + "->" + Names.Id(p.Name) + " = ::sys::unbox_any<" + pt + ">(v); }";
                    }
                    else
                    {
                        get = "[](Object* o) -> Object* { return ::sys::box_any<" + pt + ">(" + self + "->" + Names.MemberName(p.GetMethod) + "()); }";
                        set = "[](Object* o, Object* v) { " + self + "->" + Names.MemberName(p.SetMethod) + "(::sys::unbox_any<" + pt + ">(v)); }";
                    }
                    f.AppendLine("  t->AddProp(u\"" + p.Name + "\", ::sys::typeof_<" + pt + ">(), " + get + ", " + set + ");");
                }
                else if (m is IMethodSymbol ms && ms.MethodKind == MethodKind.Ordinary && !ms.IsStatic && !ms.IsGenericMethod
                         && ms.Parameters.Length == 0 && !ms.IsAbstract && !isStruct && !ms.IsImplicitlyDeclared)
                {
                    var call = self + "->" + Names.MemberName(ms) + "()";
                    string body = ms.ReturnsVoid ? call + "; return nullptr;" : "return ::sys::box_any<" + Names.Type(ms.ReturnType) + ">(" + call + ");";
                    f.AppendLine("  t->AddMethod(u\"" + ms.Name + "\", [](Object* o) -> Object* { " + body + " });");
                }
                // GC roots for static storage
                if (m is IFieldSymbol sf && sf.IsStatic && !sf.IsConst && !sf.IsImplicitlyDeclared && !Names.IsPrimitive(sf.Type) && sf.Type.TypeKind != TypeKind.Enum)
                    roots.AppendLine("  ::sys::gc_root(&" + cn + "::" + Names.Id(sf.Name) + ", sizeof(" + cn + "::" + Names.Id(sf.Name) + "));");
                if (m is IPropertySymbol sp && sp.IsStatic && !Names.IsPrimitive(sp.Type) && sp.Type.TypeKind != TypeKind.Enum)
                {
                    if (Decls.IsFieldLike(sp)) roots.AppendLine("  ::sys::gc_root(&" + cn + "::" + Names.Id(sp.Name) + ", sizeof(void*) > sizeof(" + cn + "::" + Names.Id(sp.Name) + ") ? sizeof(void*) : sizeof(" + cn + "::" + Names.Id(sp.Name) + "));");
                    else if (Decls.IsAutoProp(sp)) roots.AppendLine("  ::sys::gc_root(&" + cn + "::__p_" + Names.Id(sp.Name) + ", sizeof(" + cn + "::__p_" + Names.Id(sp.Name) + "));");
                }
                if (m is IEventSymbol se && se.IsStatic)
                    roots.AppendLine("  ::sys::gc_root(&" + cn + "::" + Names.Id(se.Name) + ", sizeof(void*));");
            }
            f.AppendLine("}");
            sb.Append(f);
            regs.Add("__reg" + fn);
            fn++;
        }
        sb.AppendLine("void __tf_register_roots() {");
        sb.Append(roots);
        sb.AppendLine("}");
        sb.AppendLine("void __tf_register_reflection() {");
        foreach (var r in regs) sb.AppendLine("  " + r + "();");
        sb.AppendLine("}");
        return sb.ToString();
    }

    static string Attrs(IFieldSymbol f, Bodies bodies)
    {
        var list = new List<string>();
        foreach (var a in f.GetAttributes())
        {
            var ac = a.AttributeClass;
            if (ac == null || !Names.IsOurs(ac)) continue;
            var args = new List<string>();
            var ctor = a.AttributeConstructor;
            for (int i = 0; i < a.ConstructorArguments.Length; i++)
                args.Add(TC(a.ConstructorArguments[i], ctor?.Parameters[i].Type, bodies));
            var s = "(::sys::gcnew<" + Names.ClassName(ac) + ">())->__ctor(" + string.Join(", ", args) + ")";
            if (a.NamedArguments.Length > 0)
            {
                var sets = string.Join(" ", a.NamedArguments.Select(na => "__a->" + Names.Id(na.Key) + " = " + TC(na.Value, null, bodies) + ";"));
                s = "([]() { auto* __a = " + s + "; " + sets + " return __a; }())";
            }
            list.Add("::sys::to_object(" + s + ")");
        }
        return list.Count == 0 ? null : string.Join(", ", list);
    }

    static string TC(TypedConstant c, ITypeSymbol target, Bodies bodies)
    {
        if (c.Kind == TypedConstantKind.Array)
        {
            var at = (IArrayTypeSymbol)(target ?? c.Type);
            return Names.ClassName(at) + "::Of({" + string.Join(", ", c.Values.Select(v => TC(v, at.ElementType, bodies))) + "})";
        }
        if (c.Kind == TypedConstantKind.Type) return "::sys::typeof_<" + Names.Type((ITypeSymbol)c.Value) + ">()";
        var t = c.Type;
        var s = bodies.Const(c.Value, t);
        if (target != null && !SymbolEqualityComparer.Default.Equals(target, t) && Names.IsPrimitive(target)) s = "static_cast<" + Names.Type(target) + ">(" + s + ")";
        if (target != null && target.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T) s = Names.Type(target) + "(" + s + ")";
        return s;
    }
}
