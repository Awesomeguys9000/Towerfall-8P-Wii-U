using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using System.Text;

var root = Path.GetFullPath(args[0]);
var outDir = Path.GetFullPath(args[1]);
// Folder holding the game's reference assemblies (FNA.dll, mscorlib.dll, System*.dll), e.g.
// TF-8P/TowerFall.app/Contents/MacOS. Third argument or TF_REFS environment variable.
var refDir = args.Length > 2 ? args[2] : (Environment.GetEnvironmentVariable("TF_REFS") ?? "");
if (refDir == "" || !File.Exists(Path.Combine(refDir, "FNA.dll")))
{
    Console.Error.WriteLine("usage: cs2cpp <cs dir> <out dir> <dir with FNA.dll, mscorlib.dll, System*.dll>");
    return 2;
}
refDir = Path.GetFullPath(refDir) + "/";
var refs = new[] { "mscorlib.dll", "System.dll", "System.Core.dll", "System.Xml.dll", "FNA.dll" }.Select(f => MetadataReference.CreateFromFile(refDir + f)).ToList();
var opts = new CSharpParseOptions(LanguageVersion.Latest);
var files = Directory.GetFiles(root, "*.cs", SearchOption.AllDirectories).OrderBy(f => f).ToList();
var trees = files.Select(f => CSharpSyntaxTree.ParseText(File.ReadAllText(f), opts, f)).ToList();
var comp = CSharpCompilation.Create("TowerFall", trees, refs, new CSharpCompilationOptions(OutputKind.ConsoleApplication, allowUnsafe: true));
var errs = comp.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
if (errs.Count > 0)
{
    foreach (var e in errs.Take(50)) Console.Error.WriteLine(e);
    Console.Error.WriteLine($"{errs.Count} C# errors");
    return 1;
}
Directory.CreateDirectory(outDir);
Directory.CreateDirectory(Path.Combine(outDir, "src"));
var decls = new Decls(comp);
var bodies = new Bodies(comp, decls);
decls.Bodies = bodies;

void WriteIfChanged(string path, string content)
{
    if (File.Exists(path) && File.ReadAllText(path) == content) return;
    File.WriteAllText(path, content);
}

WriteIfChanged(Path.Combine(outDir, "tf_fwd.h"), decls.EmitFwd());
WriteIfChanged(Path.Combine(outDir, "tf_types.h"), decls.EmitTypes());
var tpl = new StringBuilder();
tpl.AppendLine("// Generated by cs2cpp. Do not edit.\n#pragma once\n#include \"tf_types.h\"");
var written = new HashSet<string>();
foreach (var t in trees)
{
    var rel = Path.GetRelativePath(root, t.FilePath);
    var (cpp, tp) = bodies.EmitFile(t);
    tpl.Append(tp);
    var name = rel.Replace('/', '_').Replace(".cs", ".cpp");
    written.Add(name);
    WriteIfChanged(Path.Combine(outDir, "src", name), "// Generated from " + rel + "\n#include \"tf_all.h\"\n" + cpp);
}
WriteIfChanged(Path.Combine(outDir, "tf_templates.h"), tpl.ToString());
WriteIfChanged(Path.Combine(outDir, "src", "__reflection.cpp"), Reflect.Emit(decls, bodies));
written.Add("__reflection.cpp");
WriteIfChanged(Path.Combine(outDir, "tf_all.h"), "#pragma once\n#include \"tf_types.h\"\n#include \"tf_templates.h\"\n");
foreach (var f in Directory.GetFiles(Path.Combine(outDir, "src")))
    if (!written.Contains(Path.GetFileName(f))) File.Delete(f);
File.WriteAllLines(Path.Combine(outDir, "externals.txt"), bodies.ExternalUses.OrderBy(x => x));
File.WriteAllLines(Path.Combine(outDir, "warnings.txt"), bodies.Warnings);
Console.WriteLine($"ok: {trees.Count} files, {bodies.ExternalUses.Count} externals, {bodies.Warnings.Count} warnings");
return 0;
